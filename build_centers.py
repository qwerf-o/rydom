# 22.10.2026 автор обзвонила центры: с детьми принимают везде, где раньше было «неизвестно».
# Явное «нет» в базе оставляем как есть.
KIDS_UNKNOWN_AS_YES = True


# 22.10.2026 решение автора: на сайте не пишем, что центр «не проверен» или «нет свежих данных».
# Условия женщина уточняет при звонке или через менеджера.
STATUS_CLAUSE = re.compile(r",\s*[^,.]*(не подтвержд|не провер|свеж)[^,.]*", re.I)
STATUS_DROP = re.compile(
    r"не подтвержд|не провер|проверить не удалось|свеж|ручная проверка|только в открытых списках"
    r"|^Данные 20\d\d[–-]?(20\d\d)?[,.]|неполн|Сайт не (работает|открывается)|Активность|по реестру юрлиц|Найден только",
    re.I,
)


def clean_status(sentence):
    sentence = re.sub(r"\s*\(данные [^)]*\)", "", sentence)
    sentence = re.sub(r"^Данные 20\d\d(–20\d\d)?:\s*", "", sentence)
    sentence = STATUS_CLAUSE.sub("", sentence)
    sentence = re.sub(r",?\s*по открытым данным", "", sentence, flags=re.I)
    sentence = sentence.strip()
    if not sentence or STATUS_DROP.search(sentence):
        return ""
    if not sentence.endswith((".", "!", "?")):
        sentence += "."
    return sentence[:1].upper() + sentence[1:]


def clean_note(text):
    parts = re.split(r"(?<=[.!?])\s+", text or "")
    keep = [p for p in parts if p and not DROP.search(p)]
    keep = [clean_status(p) for p in keep]
    keep = [p for p in keep if p]
    note = " ".join(keep)
    note = re.sub(r"^По карте:\s*", "", note)
    note = note.replace("По карте: ", "")
    note = note.replace("Только данные карты", "Есть только в открытых списках")
    note = note.replace("только данные карты", "есть только в открытых списках")
    note = note.replace("По карте", "По открытым данным").replace("по карте", "по открытым данным")
    note = note[:1].upper() + note[1:]
    # второй проход: после замен выше снова убираем пометки о статусе
    parts = [clean_status(p) for p in re.split(r"(?<=[.!?])\s+", note) if p]
    return " ".join(p for p in parts if p).strip()


# Подписи к телефонам, где было название улицы (это почти адрес)
PHONE_FIX = {"Кандинского 8 (914)": "второй центр 8 (914)"}


def clean_phone(text):
    text = re.sub(r"\s*\(по карте\)", "", text or "").strip()
    for a, b in PHONE_FIX.items():
        text = text.replace(a, b)
    return text


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    out = []
    missing = set()
    for x in data:
        if x.get("tier") in HIDE_TIERS or x.get("inoagent") == "yes":
            continue
        if x.get("site") in HIDE_SITES:
            continue
        region = x.get("region", "")
        national = region == "Вся Россия"
        geo = None if national else GEO.get(region)
        if not national and geo is None:
            missing.add(region)
        name = NAME_FIX.get(x["name"], x["name"])
        out.append({
            "id": hashlib.md5(name.encode("utf-8")).hexdigest()[:6],
            "name": name,
            "region": region,
            "city": x.get("city", ""),
            "type": x.get("type", ""),
            "services": x.get("services", []),
            "kids": "yes" if KIDS_UNKNOWN_AS_YES and x.get("kids", "unknown") == "unknown" else x.get("kids", "unknown"),
            "noreg": x.get("noreg", "unknown"),
            "h24": x.get("h24", "unknown"),
            "phone": clean_phone(x.get("phone")),
            "site": x.get("site", ""),
            "religious": x.get("religious") == "yes" or x.get("type") == "религиозная",
            "note": clean_note(x.get("notes")),
            "rank": TIER_RANK.get(x.get("tier"), 3),
            "checked": "",  # дата проверки звонком, например "24.10.2026"
            "updated": x.get("updatedAt", ""),
            "national": national,
            "geo": geo,
        })
    out.sort(key=lambda c: (c["rank"], c["name"]))
    js = (
        "// Сгенерировано скриптом data/build_centers.py из данные/centers.json. Руками не править.\n"
        "// База центров помощи проекта «рядом».\n"
        "window.CENTERS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
    )
    OUT.write_text(js, encoding="utf-8")
    print(f"centers.js: {len(out)} центров, из них всероссийских {sum(c['national'] for c in out)}")
    if missing:
        print("Нет координат для регионов:", ", ".join(sorted(missing)))


if __name__ == "__main__":
    main()
